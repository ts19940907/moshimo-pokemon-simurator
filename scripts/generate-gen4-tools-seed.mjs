function isJaLanguage(name) {
  const n = String(name ?? "").toLowerCase();
  return n === "ja" || n === "ja-hrkt";
}

function pickJapaneseDescription(item) {
  const entries = item.flavor_text_entries ?? [];
  const preferred = [
    "platinum",
    "heartgold-soulsilver",
    "diamond-pearl",
    "emerald",
    "firered-leafgreen",
    "ruby-sapphire",
    "black-white",
  ];
  for (const vg of preferred) {
    const hit = entries.find(
      (f) => isJaLanguage(f.language?.name) && f.version_group?.name === vg,
    );
    const text = hit?.text ?? hit?.flavor_text;
    if (text) return String(text).replace(/\s+/g, " ").trim();
  }
  const anyJa = entries.find((f) => isJaLanguage(f.language?.name));
  const text = anyJa?.text ?? anyJa?.flavor_text;
  return text ? String(text).replace(/\s+/g, " ").trim() : null;
}

async function main() {
  const specs = [
    ...GEN3_ITEMS.map((name) => ({ name, generation: 3 })),
    ...GEN4_ITEMS.map((name) => ({ name, generation: 4 })),
  ];
  const tools = (
    await mapPool(specs, 8, async ({ name, generation }) => {
      const item = await fetchJson(`https://pokeapi.co/api/v2/item/${name}`);
      return {
        pokeapi_id: item.id,
        name_ja: pickName(item.names) ?? item.name,
        name_en: pickName(item.names, ["en"]) ?? item.name,
        category: item.category?.name ?? null,
        description: pickJapaneseDescription(item),
        introduced_generation: generation,
        available_generations: MASK_BY_GENERATION[generation],
      };
    })
  ).sort((a, b) => a.pokeapi_id - b.pokeapi_id);

  const lines = [
    "-- Gen3 + Gen4 battle holdable tools (additive UPSERT).",
    "-- Generated by scripts/generate-gen4-tools-seed.mjs",
    "insert into moshimo.tools (id, pokeapi_id, name_ja, name_en, category, description, effect_code, effect_meta, introduced_generation, available_generations) values",
    tools
      .map(
        (t) =>
          `(${[
            sqlStr(seedUuid(t.pokeapi_id)),
            t.pokeapi_id,
            sqlStr(t.name_ja),
            sqlStr(t.name_en),
            sqlStr(t.category),
            sqlStr(t.description),
            "NULL",
            "'{}'::jsonb",
            t.introduced_generation,
            t.available_generations,
          ].join(", ")})`,
      )
      .join(",\n"),
    "on conflict (pokeapi_id, available_generations) do update set",
    "  name_ja = excluded.name_ja,",
    "  name_en = excluded.name_en,",
    "  category = excluded.category,",
    "  description = excluded.description,",
    "  introduced_generation = excluded.introduced_generation,",
    "  updated_at = now();",
    "",
  ];

  fs.writeFileSync(path.join(root, "supabase/seed/gen4_tools.sql"), lines.join("\n"));
  fs.writeFileSync(
    path.join(root, "src/data/gen4-tools.json"),
    `${JSON.stringify(tools, null, 2)}\n`,
  );
  console.log(
    `wrote supabase/seed/gen4_tools.sql, src/data/gen4-tools.json (${tools.length} tools: ${tools.filter((t) => t.introduced_generation === 3).length} Gen3, ${tools.filter((t) => t.introduced_generation === 4).length} Gen4)`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
