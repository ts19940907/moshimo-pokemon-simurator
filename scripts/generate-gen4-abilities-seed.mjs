/**
 * Generate Gen4 ability master + pokemon↔ability junction seeds from PokeAPI.
 *
 * - Abilities: all introduced in generation-iv (Gen4–9)
 * - Links: dex 1–493 + alternate forms, non-hidden abilities as of Gen4
 *   (via past_abilities). Existing Gen3–9 links that changed in Gen4 are
 *   narrowed to Gen3 and a Gen4–9 link is added (bitwise OR when unchanged).
 *
 * Run after gen4_pokemon.sql.
 * Usage: node scripts/generate-gen4-abilities-seed.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GEN4_9, gen4StagingTargets } from "./lib/gen4Forms.mjs";
import { abilitiesForGeneration } from "./lib/pokeapiAbilities.mjs";
import {
  fetchJson,
  generationFromUrl,
  idFromUrl,
  mapPool,
  pickName,
  seedUuid,
  sqlStr,
} from "./lib/pokeapiFetch.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RULES_GENERATION = 4;

function isJaLanguage(name) {
  const n = String(name ?? "").toLowerCase();
  return n === "ja" || n === "ja-hrkt";
}

function pickJapaneseDescription(ability) {
  const entries = ability.flavor_text_entries ?? [];
  const preferred = [
    "platinum",
    "diamond-pearl",
    "heartgold-soulsilver",
    "black-white",
    "x-y",
    "sun-moon",
    "sword-shield",
  ];
  for (const vg of preferred) {
    const hit = entries.find(
      (f) => isJaLanguage(f.language?.name) && f.version_group?.name === vg,
    );
    const text = hit?.flavor_text ?? hit?.text;
    if (text) return String(text).replace(/\s+/g, " ").trim();
  }
  const anyJa = entries.find((f) => isJaLanguage(f.language?.name));
  const text = anyJa?.flavor_text ?? anyJa?.text;
  return text ? String(text).replace(/\s+/g, " ").trim() : null;
}

async function main() {
  const generation = await fetchJson("https://pokeapi.co/api/v2/generation/4/");
  const abilityRefs = generation.abilities ?? [];

  console.log(`Fetching ${abilityRefs.length} Gen4 abilities…`);
  const abilities = (
    await mapPool(abilityRefs, 8, async (ref) => {
      const detail = await fetchJson(ref.url);
      return {
        pokeapi_id: idFromUrl(ref.url, "ability"),
        name_ja: pickName(detail.names) ?? detail.name,
        name_en: pickName(detail.names, ["en"]) ?? detail.name,
        introduced_generation: generationFromUrl(detail.generation?.url) ?? 4,
        available_generations: GEN4_9,
        description: pickJapaneseDescription(detail),
      };
    })
  ).sort((a, b) => a.pokeapi_id - b.pokeapi_id);

  console.log("Resolving staging targets…");
  const targets = await gen4StagingTargets();

  console.log(`Fetching ability links for ${targets.length} pokemon…`);
  const linkRows = [];
  await mapPool(targets, 6, async (target) => {
    const pokemon = await fetchJson(`https://pokeapi.co/api/v2/pokemon/${target.pokemon}/`);
    for (const row of abilitiesForGeneration(pokemon, RULES_GENERATION)) {
      if (row.is_hidden) continue;
      const slot = Number(row.slot);
      if (slot !== 1 && slot !== 2) continue;
      linkRows.push({
        dex_no: target.dex,
        name_en: target.nameEn,
        pokeapi_ability_id: idFromUrl(row.ability.url, "ability"),
        slot,
      });
    }
  });
  linkRows.sort(
    (a, b) =>
      a.dex_no - b.dex_no ||
      String(a.name_en).localeCompare(String(b.name_en)) ||
      a.slot - b.slot,
  );

  fs.writeFileSync(
    path.join(root, "src/data/gen4-abilities.json"),
    `${JSON.stringify(abilities, null, 2)}\n`,
  );
  fs.writeFileSync(
    path.join(root, "src/data/gen4-pokemon-abilities.json"),
    `${JSON.stringify(linkRows, null, 2)}\n`,
  );

  const abilitiesSql = `-- Gen4 ability master (UPSERT). Regenerated by scripts/generate-gen4-abilities-seed.mjs
insert into moshimo.abilities (
  id,
  pokeapi_id,
  name_ja,
  name_en,
  introduced_generation,
  available_generations,
  description
) values
${abilities
  .map(
    (a) =>
      `(${sqlStr(seedUuid(a.pokeapi_id))}, ${a.pokeapi_id}, ${sqlStr(a.name_ja)}, ${sqlStr(a.name_en)}, ${a.introduced_generation}, ${a.available_generations}, ${sqlStr(a.description)})`,
  )
  .join(",\n")}
on conflict (id) do update set
  pokeapi_id = excluded.pokeapi_id,
  name_ja = excluded.name_ja,
  name_en = excluded.name_en,
  introduced_generation = excluded.introduced_generation,
  available_generations = excluded.available_generations,
  description = excluded.description;
`;

  const setupSql = `-- 1/3 setup: staging for Gen4 pokemon↔ability links
create table if not exists moshimo._seed_gen4_pokemon_abilities (
  dex_no integer not null,
  name_en text null,
  pokeapi_ability_id integer not null,
  slot smallint not null check (slot in (1, 2))
);
truncate table moshimo._seed_gen4_pokemon_abilities;
`;

  const valuesSql = `-- 2/3 values
insert into moshimo._seed_gen4_pokemon_abilities (dex_no, name_en, pokeapi_ability_id, slot) values
${linkRows
  .map((r) => `(${r.dex_no}, ${sqlStr(r.name_en)}, ${r.pokeapi_ability_id}, ${r.slot})`)
  .join(",\n")};
`;

  const finalizeSql = `-- 3/3 finalize: Gen4 links. Existing links keep their Gen1–3 bits only,
-- then Gen4–9 links are OR'ed in (unchanged abilities end up Gen3–9 again).
delete from moshimo.pokemon_abilities pa
using moshimo.pokemon p
where pa.pokemon_id = p.id
  and (p.available_generations & 8) <> 0
  and (pa.available_generations & 7) = 0;

update moshimo.pokemon_abilities pa
set available_generations = pa.available_generations & 7
from moshimo.pokemon p
where pa.pokemon_id = p.id
  and (p.available_generations & 8) <> 0
  and (pa.available_generations & 8) <> 0;

insert into moshimo.pokemon_abilities (
  pokemon_id,
  ability_id,
  slot,
  available_generations
)
select distinct
  p.id,
  a.id,
  s.slot,
  ${GEN4_9}
from moshimo._seed_gen4_pokemon_abilities s
join moshimo.pokemon p
  on p.dex_no = s.dex_no
 and (s.name_en is null or p.name_en = s.name_en)
 and (p.available_generations & 8) <> 0
join moshimo.abilities a
  on a.pokeapi_id = s.pokeapi_ability_id
on conflict (pokemon_id, ability_id, slot) do update set
  available_generations =
    moshimo.pokemon_abilities.available_generations | excluded.available_generations;

-- Gen3+ rows added here (Deoxys forms) reuse their Gen4 links for Gen3.
update moshimo.pokemon_abilities pa
set available_generations = pa.available_generations | 4
from moshimo.pokemon p
where pa.pokemon_id = p.id
  and (p.available_generations & 4) <> 0
  and (pa.available_generations & 8) <> 0
  and not exists (
    select 1
    from moshimo.pokemon_abilities x
    where x.pokemon_id = p.id
      and (x.available_generations & 4) <> 0
  );

-- Legacy ability columns on Gen4+-only rows (shared Gen3 rows keep Gen3 values).
update moshimo.pokemon p
set ability1_id = x.ability_id
from (
  select distinct on (pa.pokemon_id) pa.pokemon_id, pa.ability_id
  from moshimo.pokemon_abilities pa
  where pa.slot = 1 and (pa.available_generations & 8) <> 0
  order by pa.pokemon_id, pa.ability_id
) x
where p.id = x.pokemon_id
  and (p.available_generations & 8) <> 0
  and (p.available_generations & 7) = 0;

update moshimo.pokemon p
set ability2_id = x.ability_id
from (
  select distinct on (pa.pokemon_id) pa.pokemon_id, pa.ability_id
  from moshimo.pokemon_abilities pa
  where pa.slot = 2 and (pa.available_generations & 8) <> 0
  order by pa.pokemon_id, pa.ability_id
) x
where p.id = x.pokemon_id
  and (p.available_generations & 8) <> 0
  and (p.available_generations & 7) = 0;

drop table if exists moshimo._seed_gen4_pokemon_abilities;
`;

  const seedDir = path.join(root, "supabase/seed");
  fs.writeFileSync(path.join(seedDir, "gen4_abilities.sql"), abilitiesSql);
  fs.writeFileSync(path.join(seedDir, "gen4_pokemon_abilities_00_setup.sql"), setupSql);
  fs.writeFileSync(path.join(seedDir, "gen4_pokemon_abilities_01_values.sql"), valuesSql);
  fs.writeFileSync(path.join(seedDir, "gen4_pokemon_abilities_99_finalize.sql"), finalizeSql);
  fs.writeFileSync(
    path.join(seedDir, "gen4_abilities_all.sql"),
    `-- Gen4 abilities + pokemon_abilities (run after gen4_pokemon.sql)
-- Regenerated by: node scripts/generate-gen4-abilities-seed.mjs

${abilitiesSql}
${setupSql}
${valuesSql}
${finalizeSql}`,
  );

  console.log(
    `Wrote ${abilities.length} abilities, ${linkRows.length} links → supabase/seed/gen4_*abilities*.sql`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
